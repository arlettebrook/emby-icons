import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "migrations");
const outputFile = join(root, "functions", "_shared", "migrations.generated.js");

const files = (await readdir(migrationsDir))
  .filter((name) => name.endsWith(".sql"))
  .sort();

const migrations = await Promise.all(
  files.map(async (id) => ({
    id,
    sql: (await readFile(join(migrationsDir, id), "utf8")).replace(/^\uFEFF/, "").replaceAll("\r\n", "\n"),
  })),
);

const source = `// Generated by scripts/build.js from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS = ${JSON.stringify(migrations, null, 2)};\n`;

await mkdir(dirname(outputFile), { recursive: true });
let previous = "";
try {
  previous = await readFile(outputFile, "utf8");
} catch {
  previous = "";
}
if (previous !== source) {
  await writeFile(outputFile, source, "utf8");
}

console.log(`Generated ${migrations.length} database migration(s) for runtime deployment.`);
